#!/usr/bin/env node
/* Writes js/data/catalog.js: the lesson index the page loads up front (titles, prerequisites, section ids and titles,
 * quiz sizes and problem titles), so that the lesson files themselves (js/data/concepts-*.js, listed in order in
 * tools/content-files.json) can load on demand.
 *   node tools/build-catalog.js
 * tools/lesson-patch.js runs it after every patch, and tests/content.test.js fails when the catalog is out of date. */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const OUT = path.join(root, 'js/data/catalog.js');

function generate(MLA) {
  const files = JSON.parse(fs.readFileSync(path.join(root, 'tools/content-files.json'), 'utf8'));
  const rows = MLA.data.concepts.map(c => {
    const e = { id: c.id, branch: c.branch, title: c.title };
    if (c.short) e.short = c.short;
    Object.assign(e, { level: c.level, minutes: c.minutes, prereqs: c.prereqs, tags: c.tags || [], summary: c.summary || '', file: c.file,
      sections: c.sections.map(s => [s.id, s.type, s.title || '']), quiz: c.quiz.length, problems: c.problems.map(p => [p.id, p.title, p.difficulty]) });
    return '    ' + JSON.stringify(e);
  });
  return '/* Generated by tools/build-catalog.js from ' + files.length + ' lesson files (' + rows.length + ' lessons). Do not edit by hand: change the\n' +
    ' * lessons, then run node tools/build-catalog.js. The page loads this index up front and each lesson file on demand. */\n' +
    '(function (global) {\n  const MLA = (global.MLA = global.MLA || {});\n  MLA.data = MLA.data || {};\n  MLA.data.catalog = {\n' +
    '  files: ' + JSON.stringify(files) + ',\n  concepts: [\n' + rows.join(',\n') + '\n  ] };\n' +
    "})(typeof globalThis !== 'undefined' ? globalThis : window);\n";
}

function write() {
  const MLA = require('../tests/_load.js').load();
  if (!MLA.content.ready) MLA.content.init();
  const text = generate(MLA);
  fs.writeFileSync(OUT, text);
  return text;
}

if (require.main === module) {
  const text = write();
  console.log('js/data/catalog.js: ' + Math.round(text.length / 1024) + ' KB');
}
module.exports = { generate, write, OUT };
