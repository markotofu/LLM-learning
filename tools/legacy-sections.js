#!/usr/bin/env node
/* Generator for the section-id migration (see migrateSections in js/core/progress.js).
 * Version 6badf8c and earlier saved "sections read" and answered checks by section *position*. This script reads the
 * lessons as they were in that version (from git history), gives their sections ids with today's rules, and writes:
 *   tests/fixtures/legacy-sections.json – the old layout of every lesson (checked by tests/content.test.js)
 *   js/data/legacy-sections.js          – only the lessons whose sections changed since (shipped to browsers)
 * Run it again whenever tests/content.test.js reports that a lesson's legacy layout no longer matches.
 * Usage: node tools/legacy-sections.js [commit]      (needs git and the repository history) */
'use strict';
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const COMMIT = process.argv[2] || '6badf8c';
const git = args => execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
const scriptsOf = html => [...html.matchAll(/<script src="([^"]+)"><\/script>/g)].map(m => m[1]).filter(s => /^js\/data\/concepts-.*\.js$/.test(s));

// Section ids for every lesson in a set of concept files, using today's id rules (util.js + branches.js).
function layouts(readFile, files) {
  const ctx = vm.createContext({ console });
  ctx.globalThis = ctx; ctx.window = ctx;
  for (const f of ['js/core/util.js', 'js/data/branches.js']) vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), ctx, { filename: f });
  for (const f of files) vm.runInContext(readFile(f), ctx, { filename: f });
  const out = {};
  for (const c of ctx.MLA.data.concepts) out[c.id] = ctx.MLA.content.sectionIds(c.sections);
  return out;
}

const oldLayouts = layouts(f => git(['show', COMMIT + ':' + f]), scriptsOf(git(['show', COMMIT + ':index.html'])));
const curLayouts = layouts(f => fs.readFileSync(path.join(root, f), 'utf8'), scriptsOf(fs.readFileSync(path.join(root, 'index.html'), 'utf8')));

const changed = {};
for (const [id, old] of Object.entries(oldLayouts)) {
  const cur = curLayouts[id] || [];
  if (JSON.stringify(cur.slice(0, old.length)) !== JSON.stringify(old)) changed[id] = old;
}

fs.mkdirSync(path.join(root, 'tests/fixtures'), { recursive: true });
fs.writeFileSync(path.join(root, 'tests/fixtures/legacy-sections.json'), JSON.stringify({ commit: COMMIT, layouts: oldLayouts }, null, 1) + '\n');
const body = Object.entries(changed).map(([id, ids]) => '    ' + JSON.stringify(id) + ': ' + JSON.stringify(ids)).join(',\n');
fs.writeFileSync(path.join(root, 'js/data/legacy-sections.js'),
  '/* ML Atlas – generated by tools/legacy-sections.js; do not edit by hand.\n' +
  ' * Section layouts (by id) of the lessons whose sections changed after version ' + COMMIT + ', the last version that saved\n' +
  ' * progress by section position. MLA.progress.migrateSections uses them to translate old saved progress once. */\n' +
  '(function (global) {\n  const MLA = global.MLA;\n  MLA.data.legacySections = {\n' + body + '\n  };\n})(typeof globalThis !== \'undefined\' ? globalThis : window);\n');
console.log(Object.keys(oldLayouts).length + ' lessons in ' + COMMIT + '; ' + Object.keys(changed).length + ' changed since: ' + Object.keys(changed).join(', '));
