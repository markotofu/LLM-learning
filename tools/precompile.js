#!/usr/bin/env node
/* Deploy step: compiles every Vue template ahead of time, so the published page can drop 'unsafe-eval' from its
 * Content-Security-Policy. Vue's in-browser template compiler needs eval; precompiled render functions do not.
 * Writes js/precompiled.js and a copy of index.html that loads it and has the stricter policy.
 *   node tools/precompile.js                    rewrites index.html in place (the deploy job does this on its copy)
 *   node tools/precompile.js --index strict.html   writes the strict page to another file (to try it locally)
 * Development is unchanged: without js/precompiled.js, Vue compiles the templates in the browser as before. */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const target = process.argv.includes('--index') ? process.argv[process.argv.indexOf('--index') + 1] : 'index.html';

const MLA = require('../tests/_load.js').load();
const Vue = global.Vue;

// Vue.compile builds its render function with new Function('Vue', code); catch the code instead of guessing it.
const RealFunction = global.Function;
let captured = null;
global.Function = function (...args) { captured = args[args.length - 1]; return RealFunction(...args); };
const byTemplate = new Map(), entries = [];
function compile(name, template) {
  if (!byTemplate.has(template)) {
    captured = null;
    const errors = [];
    Vue.compile(template, { onError: e => errors.push(e.message) });
    if (errors.length) throw new Error('Template of ' + name + ' does not compile: ' + errors.join('; '));
    if (!captured) throw new Error('No render code was produced for ' + name);
    byTemplate.set(template, captured);
  }
  const code = byTemplate.get(template).split('\n').map(l => l.trim()).join('\n');   // Vue's generated strings never span lines
  entries.push('  R[' + JSON.stringify(name) + '] = rc(function (Vue) {\n' + code + '\n}(Vue));');
}
for (const name of Object.keys(MLA.components).sort()) {
  const c = MLA.components[name];
  if (c && typeof c.template === 'string') compile(name, c.template);
}
compile('root', MLA.app.Root.template);
global.Function = RealFunction;

const header = '/* Generated by tools/precompile.js at deploy time: the render functions of every Vue template, so the page\n' +
  ' * runs without eval. Do not edit; do not commit. */\n';
// _rc marks a render function as runtime-compiled (it uses with(ctx)), so Vue gives it the matching proxy.
const body = '(function (Vue) {\n  var R = {}, rc = function (f) { f._rc = true; return f; };\n' + entries.join('\n') + '\n  window.MLA_RENDER = R;\n}(Vue));\n';
fs.writeFileSync(path.join(root, 'js/precompiled.js'), header + body);

let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const vueTag = '<script src="vendor/vue.global.prod.js"></script>';
if (!html.includes(vueTag)) throw new Error('index.html does not load ' + vueTag);
const strictFrom = "script-src 'self' 'unsafe-eval' ", strictTo = "script-src 'self' ";
if (!html.includes(strictFrom)) throw new Error("index.html's script-src has no 'unsafe-eval' to remove");
html = html.replace(strictFrom, strictTo).replace(vueTag, vueTag + '\n  <script src="js/precompiled.js"></script>');
fs.writeFileSync(path.join(root, target), html);
console.log('Precompiled ' + entries.length + ' templates (' + byTemplate.size + ' distinct) into js/precompiled.js; wrote ' + target + " without 'unsafe-eval'");
